const editorialAuthor = {
  authorName: "Bitara Editorial Team",
  authorRole: "Regional Growth Research",
}

function createSupplementalPost(seed: SupplementalBlogSeed): BlogPost {
  return {
    slug: seed.slug,
    title: seed.title,
    description: seed.description,
    excerpt: seed.excerpt,
    category: seed.category,
    readTime: "8 min read",
    publishedAt: seed.publishedAt,
    image: seed.image,
    alt: seed.alt,
    ...editorialAuthor,
    intro: `${seed.marketLabel} buyers searching for ${seed.primaryKeyword} are usually comparing credibility, delivery quality, and whether the team can solve ${seed.painPoint}. Strong websites and SaaS pages need to answer those concerns quickly if they want to earn trust and qualified leads.`,
    pullQuote: `${seed.primaryKeyword} performs best when the website proves clarity, trust, and delivery maturity at the same time.`,
    sections: [
      {
        title: `What ${seed.marketLabel} clients look for first`,
        paragraphs: [
          `Search intent around ${seed.primaryKeyword} is usually commercial, not casual. Buyers want to know whether the agency understands the market, can communicate clearly, and has the technical depth to deliver without unnecessary complexity.`,
          `That means the page should explain the service, show real proof, and reduce doubt around timeline, quality, and ownership before the visitor needs to ask.`,
        ],
      },
      {
        title: "What the digital experience needs to prove",
        paragraphs: [
          `A weak page often lists services without showing why the offer is valuable. For ${seed.serviceLine.toLowerCase()}, the site should prove ${seed.valueAngle} while staying easy to use on mobile, because many prospects will evaluate the company from a phone first.`,
          `Good structure, clear copy, fast performance, and trustworthy project examples usually do more for conversion than generic claims about being creative or innovative.`,
        ],
      },
      {
        title: `How Bitara approaches ${seed.serviceLine.toLowerCase()}`,
        paragraphs: [
          `Bitara approaches ${seed.serviceLine.toLowerCase()} by connecting strategy, design, engineering, and SEO foundations in one workflow. That helps businesses in ${seed.marketLabel} launch digital products that look professional and still support measurable business goals.`,
          `The goal is not only to publish a better-looking website. It is to create an experience that supports search visibility, stronger trust, and cleaner inquiry flow for the right kind of client.`,
        ],
      },
    ],
    keyTakeaways: [
      `${seed.primaryKeyword} is a high-intent search term and should be supported by real proof.`,
      `Pages targeting ${seed.marketLabel} visitors need stronger mobile clarity and trust signals.`,
      `${seed.serviceLine} should be explained in business terms, not only design language.`,
      `SEO, structure, and conversion planning should support the same commercial goal.`,
    ],
    keywords: [seed.primaryKeyword, ...seed.secondaryKeywords],
  }
}

